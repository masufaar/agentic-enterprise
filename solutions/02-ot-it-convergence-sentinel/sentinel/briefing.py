"""Agent 4, briefing: writes one page for the crisis team, in the language of
production rather than of security alerts. It reads the incident and the priced
options and adds no figure of its own.
"""
from . import act

AGENT = "ot-briefing"


def eur(amount: float) -> str:
    return f"EUR {amount:,.0f}"


def _clock(text: str) -> str:
    return text[11:16]


def _stopped(option: dict) -> str:
    if not option["lines_stopped"]:
        return "none"
    parts = []
    for line in option["lines_stopped"]:
        extra = f" plus {line['restart_hours']} h restart" if line["restart_hours"] else ""
        parts.append(f"{line['name']}: {line['hours_stopped']:g} h{extra}")
    return "; ".join(parts)


def page(incident: dict, assessment: dict, held: list[dict], unrelated: list[dict],
         plant: dict, approver: str) -> str:
    production = assessment["production"]
    names = {line["id"]: line["name"] for line in production["lines"]}
    options = assessment["options"]
    best = next(o for o in options if o["points"] == assessment["recommended"])
    nothing = next(o for o in options if not o["points"])
    widest = max(options, key=lambda o: o["cost_eur"])
    waiting = [h for h in held if h["decision"] == "require_approval"]
    rate = production["cost_per_stopped_line_hour_eur"]
    lines = [
        f"# Incident {incident['id']} at {plant['plant']['name']}: picture for the crisis team",
        "",
        "Generated by `python -m sentinel run`. Synthetic data, simulated tools, fixed rules, no language model. "
        "Every euro figure is calculated from the assumptions listed at the end; none is a measured loss.",
        "",
        "## In short",
        "",
        f"An intruder moved from the office network to the plant floor between {_clock(incident['first_seen'])} "
        f"and {_clock(incident['last_seen'])} UTC and now controls {len(incident['footholds'])} devices. "
        f"{len(nothing['lines_still_reachable'])} production lines are within reach. "
        f"The recommended response costs {eur(best['cost_eur'])} in lost output and leaves no line within reach. "
        f"Disconnecting the widest area instead would cost {eur(widest['cost_eur'])}. "
        f"Nothing has been disconnected: the request is waiting for the {approver}.",
        "",
        "## What happened",
        "",
        "| Time (UTC) | Seen by | From | To | What |",
        "|---|---|---|---|---|",
    ]
    for step in incident["timeline"]:
        lines.append(f"| {_clock(step['time'])} | {step['side']} tool | {step['origin']} | {step['target']} | {step['text']} |")
    lines += [
        "",
        f"The {len(incident['alerts'])} alerts above came from two separate tools and were joined because they share "
        f"devices or accounts within one hour. Account used from a device it does not belong to: {', '.join(incident['accounts_moved']) or 'none'}.",
        "",
        "## What each response costs",
        "",
        "| Response | Lost output | Lines stopped | Lines the intruder can still reach | Still at stake if those are encrypted |",
        "|---|---|---|---|---|",
    ]
    for option in options:
        mark = " **(recommended)**" if option is best else ""
        reach = ", ".join(names[l] for l in option["lines_still_reachable"]) or "none"
        lines.append(f"| {option['name']}{mark} | {eur(option['cost_eur'])} | {_stopped(option)} | {reach} | "
                     f"{eur(option['still_at_stake_eur'])} |")
    lines += [
        "",
        "## Recommendation",
        "",
        f"{best['name']}. It is the cheapest response that leaves no production line within the intruder's reach. "
        f"It costs {eur(widest['cost_eur'] - best['cost_eur'])} less than the widest disconnection.",
        "",
        "## Waiting for a decision",
        "",
    ]
    if waiting:
        lines += ["| Request | Waiting for | Rules that hold it |", "|---|---|---|"]
        lines += [f"| {h['what']} | {approver} | {h['rule'].replace(',', ', ')} |" for h in waiting]
        lines += ["", "The agent that asked cannot release its own request, and no other role can release it. "
                  "The release is given in the AI Governance Control Tower and recorded there."]
    else:
        lines.append("No request is waiting.")
    lines += ["", "## Alerts set aside as unrelated", ""]
    lines += [f"- {u['id']}: {u['text']}" for u in unrelated] or ["None."]
    lines += [
        "",
        "## Assumptions behind the figures",
        "",
        f"- Cost of one stopped line-hour: {eur(rate)} (company profile).",
    ]
    for a in production["assumptions"].values():
        value = "yes" if a["value"] is True else f"{a['value']} {a.get('unit', '')}".strip()
        lines.append(f"- {a['basis']} Value used: {value}.")
    lines += [f"- {p['name']}: held for {p['hold_hours']} hours. {p['hold_basis']}" for p in plant["isolation_points"]]
    lines += [f"- {l['name']}: {l['restart_extra_hours']} further hours after any stop. {l['restart_basis']}"
              for l in production["lines"] if l.get("restart_extra_hours")]
    lines += [
        "- Lost output is counted only for hours in which the schedule says the line would have run.",
        "",
        "## What this page is not",
        "",
        "- Not a detection result: the alerts were written by hand for one scenario.",
        "- Not a forecast: the figures follow from the assumptions above and change with them.",
        "- Not a notification to the regulator. That is designed, not built.",
        "",
    ]
    return "\n".join(lines)


def brief(gateway, incident: dict, assessment: dict, held: list[dict], unrelated: list[dict],
          plant: dict) -> str:
    act(gateway, AGENT, "incident.read", {"incident": incident["id"]})
    approver = gateway.registry["ot-response"]["owner"]
    text = page(incident, assessment, held, unrelated, plant, approver)
    act(gateway, AGENT, "report.write", {"report": f"incident {incident['id']}, crisis team picture",
                                         "characters": len(text)})
    return text
