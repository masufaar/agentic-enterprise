"""Board report: one page that answers the board's questions from data that already exists.

Nothing new is measured or stored here. The page is put together from the registry
(who runs what), the risk classification (proposed tiers) and the latest red-team
campaign (what was contained, what got through, what waits for a person).

Version 0 is generated on demand. A fixed quarterly schedule, trends over time and
cost and benefit per agent are designed, not built.
"""
from . import registry as registry_module
from .classifier import ORDER, classify
from .reach import LEVELS, reach

CONTAINED = ("blocked", "held", "capped")
CONCENTRATION = 0.5  # assumption: more than half of the waiting items on one role is worth a line


def figures(report: dict, registry: dict | None = None, stopped: list[str] | None = None) -> dict:
    """Every number on the page, in one place, so that tests can check them."""
    registry = registry or registry_module.load()
    cards = list(registry.values())
    tiers = {card["id"]: classify(card) for card in cards}
    far = {card["id"]: reach(card) for card in cards}
    attacks = [r for r in report["results"] if r["category"] != "control"]
    controls = [r for r in report["results"] if r["category"] == "control"]
    waiting = report.get("waiting_by_approver", {})
    return {
        "agents": len(cards),
        "approved": [c["id"] for c in cards if c["approval"].get("status") == "approved"],
        "not_approved": [c["id"] for c in cards if c["approval"].get("status") != "approved"],
        "stopped": stopped or [],
        "today": {state: sum(c["today"] == state for c in cards) for state in registry_module.TODAY},
        "by_reach": {level: [c for c in cards if far[c["id"]]["level"] == level] for level in LEVELS},
        "far_on_their_own": [c for c in cards if far[c["id"]]["level"] >= 3 and far[c["id"]]["on_its_own"]],
        "by_tier": {t: [c for c in cards if tiers[c["id"]]["tier"] == t] for t in reversed(ORDER)},
        "signed_off": sum(1 for t in tiers.values() if t["signed_off_by"]),
        "by_autonomy": {a: sum(c["autonomy"] == a for c in cards) for a in ("advise", "act_with_approval", "act")},
        "attacks": len(attacks),
        "contained": sum(r["outcome"] in CONTAINED for r in attacks),
        "breaches": [r for r in attacks if r["outcome"] == "BREACH"],
        "controls": len(controls),
        "controls_ok": sum(r["outcome"] == "ok" for r in controls),
        "attack_rows": attacks,
        "waiting": dict(sorted(waiting.items(), key=lambda x: -x[1])),
    }


def _today(counts: dict) -> str:
    """What stands behind the cards, in the words of the registry. An agent is a language model in a loop."""
    words = {"agent working": "agents working", "agent in build": "agents in build",
             "fixed code": "steps of fixed code without a model", "designed": "designed agents with nothing behind the card yet"}
    parts = [f"{counts[state]} {words[state]}" for state in words if counts.get(state)]
    running = "" if counts.get("agent working") else " No agent is rated working yet."
    return "; ".join(parts) + "." + running


def _share(part: int, whole: int) -> str:
    return f"{part} of {whole} ({round(100 * part / whole)}%)" if whole else "none run"


def _unaltered(check: str) -> str:
    """The audit check in the board's words; the technical result stays in the red-team results."""
    if check == "chain intact":
        return "Yes. Every entry was checked against the one before it and none was changed."
    return f"**No.** The check failed ({check}). The record cannot be relied on until this is explained."


def _breakdown(rows: list[dict], key: str) -> list[str]:
    lines = []
    for value in dict.fromkeys(r[key] for r in rows):
        group = [r for r in rows if r[key] == value]
        count = lambda outcome: sum(r["outcome"] == outcome for r in group)
        lines.append(f"| {value.replace('_', ' ')} | {len(group)} | {count('blocked')} | {count('held')} | "
                     f"{count('capped')} | {count('BREACH')} |")
    return lines


def page(report: dict, fixes: dict | None = None, registry: dict | None = None,
         stopped: list[str] | None = None, rules: int | None = None) -> str:
    f, s, fixes = figures(report, registry, stopped), report["summary"], fixes or {}
    waiting_total = sum(f["waiting"].values())
    top = next(iter(f["waiting"].items()), None)
    lines = [
        "# AI risk report for the board", "",
        f"Generated by `python -m control_tower board` from the agent registry and the red-team campaign "
        f"run at {s['run_at']} (UTC). All data is synthetic and belongs to the fictional company "
        "Halden Industrial. Every figure on this page is measured in this folder.", "",
        "Version 0 is generated on demand. A fixed quarterly schedule, trends over time and cost and "
        "benefit per agent are designed, not built.", "",
        "## At a glance", "",
        "| Question | Answer |", "|---|---|",
        f"| How many cards are in the agent registry? | {f['agents']} |",
        f"| What stands behind them today? | {_today(f['today'])} |",
        f"| How many are approved to act? | {len(f['approved'])}; {len(f['not_approved'])} registered but not yet approved |",
        f"| How many are switched off right now? | {'all' if 'all' in f['stopped'] else len(f['stopped'])} |",
        *([f"| How many company rules are enforced? | {rules}, and one daily volume limit |"] if rules else []),
        f"| How many attacks were contained in the latest campaign? | {_share(f['contained'], f['attacks'])} |",
        f"| How many got through? | **{len(f['breaches'])}** |",
        f"| Was legitimate work still allowed? | {f['controls_ok']} of {f['controls']} actions |",
        f"| How many actions wait for a named person? | {waiting_total} |",
        f"| Is the record of decisions unaltered? | {_unaltered(s['audit_chain'])} |", "",
        "Contained means refused outright, held for a named person, or stopped at the agent's daily allowance.", "",
        "## Points for the board's attention", "",
    ]
    points = []
    for r in f["breaches"]:
        points.append(f"**Open finding {r['id']}.** {r['story']} {fixes.get(r['id'], 'No fix designed yet.')}")
    if top and waiting_total and top[1] / waiting_total > CONCENTRATION:
        points.append(f"**Approver load.** {top[1]} of {waiting_total} waiting actions fall on one role, "
                      f"the {top[0]}. Too many requests wear an approver down. Reducing the load is designed, not built.")
    high = f["by_tier"]["high"] + f["by_tier"]["prohibited"]
    if high:
        points.append("**High-risk agents.** " + "; ".join(f"{c['name']} (owner: {c['owner']})" for c in high)
                      + (". They may read on their own; every other action waits for a named person."
                         if len(high) > 1 else
                         ". It may read on its own; every other action it takes waits for a named person."))
    if f["far_on_their_own"]:
        points.append("**Acting on their own beyond reading and writing.** "
                      + "; ".join(f"{c['name']} (owner: {c['owner']}, {registry_module.TODAY[c['today']].lower()})"
                                  for c in f["far_on_their_own"])
                      + ". Their permissions reach accounts, systems or money and they are registered to act without "
                      "a person. What limits them is the permission list and the company rules. The legal tier does "
                      "not show this, which is why the reach of action is rated separately below.")
    if f["signed_off"] < f["agents"]:
        points.append(f"**Ratings awaiting sign-off.** {f['agents'] - f['signed_off']} of {f['agents']} "
                      "proposed legal tiers and all reach ratings have no human sign-off. Recording the sign-off is "
                      "designed, not built, and the legal references are not yet verified against the official texts.")
    if f["not_approved"]:
        points.append("**Registered but not approved.** " + ", ".join(registry_name(f, i) for i in f["not_approved"])
                      + ". The gateway refuses every action of an agent that is not approved.")
    lines += [f"{n}. {p}" for n, p in enumerate(points, 1)] or ["None."]
    lines += ["", "## Cards by reach of action", "",
              "How far the permissions of each card go inside the company, worked out from its permission list.", "",
              "| Reach | Cards | Registered to act without a person | Which |", "|---|---|---|---|"]
    for level, cards in sorted(f["by_reach"].items(), reverse=True):
        alone = sum(c["autonomy"] == "act" for c in cards)
        lines.append(f"| {level}: {LEVELS[level]} | {len(cards)} | {alone} | {', '.join(c['name'] for c in cards) or '-'} |")
    lines += ["", "## Cards by proposed legal tier", "",
              "| Proposed EU AI Act tier | Cards | Which |", "|---|---|---|"]
    for tier, cards in f["by_tier"].items():
        lines.append(f"| {tier} | {len(cards)} | {', '.join(c['name'] for c in cards) or '-'} |")
    lines += ["", "Tiers are proposals from fixed rules, not legal advice. See the "
              "[agent inventory](agent-inventory.md) for owner, approver, both ratings and what stands behind each card.", "",
              "## Cards by level of autonomy", "", "| Level | Cards |", "|---|---|",
              f"| Advise only | {f['by_autonomy']['advise']} |",
              f"| Act, with approval for every action that is not a read | {f['by_autonomy']['act_with_approval']} |",
              f"| Act within their permissions and the company rules | {f['by_autonomy']['act']} |", "",
              "## Latest campaign by type of attack", "",
              "| Type | Attacks | Refused | Held for a person | Capped | Got through |", "|---|---|---|---|---|---|",
              *_breakdown(f["attack_rows"], "category"), "",
              "## Latest campaign by attacked agent", "",
              "| Agent | Attacks | Refused | Held for a person | Capped | Got through |", "|---|---|---|---|---|---|",
              *_breakdown(f["attack_rows"], "agent"), "",
              "Every case is listed in the [red-team results](redteam-latest.md).", "",
              "## Waiting for a named person", "", "| Approver | Actions waiting |", "|---|---|",
              *[f"| {who} | {count} |" for who, count in f["waiting"].items()], "",
              "See [what the approver sees](approvals-latest.md).", "",
              "## What this report does not cover", "",
              "- The attacks are scripted and the systems behind the gateway are simulated. No live language model is tested yet.",
              "- No trend: the campaign runs on demand and keeps no history. A nightly run is designed.",
              "- No cost and no benefit per agent. That is the AI Value Ledger, which is designed.",
              "- Unregistered AI use outside the gateway is not detected. Discovery of such use is designed.", ""]
    return "\n".join(lines)


def registry_name(f: dict, agent_id: str) -> str:
    for cards in f["by_tier"].values():
        for card in cards:
            if card["id"] == agent_id:
                return card["name"]
    return agent_id
