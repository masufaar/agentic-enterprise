"""Command line for the Control Tower.

  python -m control_tower inventory            list every agent with owner, approver and risk tier
  python -m control_tower check AGENT TOOL [key=value ...] [--approved-by ROLE]
  python -m control_tower approvals            list what is waiting for a named person
  python -m control_tower release ITEM --as ROLE
  python -m control_tower refuse ITEM --as ROLE [reason]
  python -m control_tower kill AGENT|all       pull the kill switch
  python -m control_tower revive AGENT|all
  python -m control_tower redteam              run the attack campaign and publish the results
  python -m control_tower verify               check the audit trail has not been altered
"""
import sys
from datetime import datetime, timezone

from . import REPORTS, STATE, redteam, registry
from .approvals import ApprovalError, Approvals
from .audit import AuditLog
from .classifier import classify
from .gateway import Gateway
from .killswitch import KillSwitch


def _value(text: str):
    try:
        return int(text)
    except ValueError:
        return text


def inventory() -> str:
    lines = ["| Agent | Solution | Accountable owner | Approved by | Autonomy | Proposed risk tier | Basis |",
             "|---|---|---|---|---|---|---|"]
    for card in registry.load().values():
        risk = classify(card)
        approver = card["approval"].get("approved_by") or "NOT APPROVED"
        lines.append(f"| {card['id']} | {card['solution'][:2]} | {card['owner']} | {approver} | "
                     f"{card['autonomy'].replace('_', ' ')} | {risk['tier']} | {risk['basis']} |")
    return "\n".join(lines)


def main(argv: list[str]) -> int:
    if not argv:
        print(__doc__)
        return 1
    command, args = argv[0], argv[1:]
    if command == "inventory":
        table = inventory()
        REPORTS.mkdir(exist_ok=True)
        (REPORTS / "agent-inventory.md").write_text(
            "# Agent inventory\n\nGenerated by `python -m control_tower inventory`. Synthetic data. "
            "Risk tiers are proposals awaiting human sign-off, not legal advice.\n\n" + table + "\n")
        print(table)
    elif command == "check":
        approved_by = None
        if "--approved-by" in args:
            index = args.index("--approved-by")
            approved_by = args[index + 1]
            args = args[:index] + args[index + 2:]
        params = {k: _value(v) for k, v in (a.split("=", 1) for a in args[2:])}
        verdict = Gateway().execute(args[0], args[1], params, approved_by=approved_by)
        print(f"{verdict['decision'].upper()}  rule={verdict['rule']}  {verdict['reason']}  "
              f"(audit record {verdict['audit_seq']})")
    elif command == "approvals":
        waiting = Approvals(Gateway()).pending()
        for item in waiting:
            print(f"Item {item['seq']}: {item['agent_name']} wants to use {item['tool']}")
            print(f"  waiting for: {item['approver']}")
            for rule, why in zip(item["rules"], item["why"]):
                print(f"  held by {rule}: {why}")
            for hint in item["look_for"]:
                print(f"  look for: {hint}")
            print(f"  request: {item['request']}")
        print(f"{len(waiting)} waiting")
    elif command in ("release", "refuse"):
        if "--as" not in args or args.index("--as") + 1 >= len(args) or not args[0].isdigit():
            print(__doc__)
            return 1
        index = args.index("--as")
        role, rest = args[index + 1], args[1:index] + args[index + 2:]
        approvals = Approvals(Gateway())
        try:
            if command == "release":
                verdict = approvals.release(int(args[0]), role)
                print(f"{verdict['decision'].upper()}  carried out={verdict['executed']}  {verdict['reason']}  "
                      f"(audit record {verdict['audit_seq']})")
            else:
                record = approvals.refuse(int(args[0]), role, " ".join(rest))
                print(f"REFUSED  (audit record {record['seq']})")
        except ApprovalError as error:
            print(f"NOT ACCEPTED  {error}")
            return 2
    elif command in ("kill", "revive"):
        target = args[0] if args else "all"
        getattr(KillSwitch(), command)(target)
        AuditLog().append({"source": "operator", "agent_id": target, "tool": f"killswitch.{command}",
                           "params": {}, "decision": "executed", "rule": "KILL", "reason": "",
                           "approved_by": None})
        print(f"{command}: {target}")
    elif command == "redteam":
        # Each campaign gets its own fresh audit trail, so results do not depend on earlier runs.
        stamp = datetime.now(timezone.utc).strftime("%Y%m%dT%H%M%S.%fZ")
        report = redteam.run(Gateway(audit=AuditLog(STATE / f"redteam-{stamp}.jsonl")))
        redteam.publish(report)
        for r in report["results"]:
            print(f"{r['id']}  {r['outcome']:<11}  {r['agent']:<24} {r['tool']:<16} rule={r['rule']}  {r['detail']}")
        print(report["summary"])
        return 0
    elif command == "verify":
        ok, message = AuditLog().verify()
        print(f"{len(AuditLog())} records, {message}")
        return 0 if ok else 2
    else:
        print(__doc__)
        return 1
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
